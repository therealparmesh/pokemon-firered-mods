# Native repeat and numeric bounds, using this ROM's controller-created state.
m.load(out/'coverage.state')
open_menu()
check(m.read('sModPage',1)==0, 'Touch-friendly Start > Mods opens Main under L=A without a button chord')
snap('controls-main');page(0);number(4,4,0);select(4);m.tap(LEFT)
check(setting(4)==25, 'Zero-minimum nature wraps left from Random to its maximum')
m.tap(RIGHT);check(setting(4)==0, 'Nature wraps right from maximum to Random')
number(2,2,1);select(2);m.tap(LEFT)
check(setting(2)==100, 'Level wraps left from one to 100')
m.tap(RIGHT);check(setting(2)==1, 'Level wraps right from 100 to one')
number(5,5,0);select(5);m.tap(LEFT)
check(setting(5)==32, 'IV selector wraps Random to the maximum encoded IV choice')
m.tap(RIGHT);check(setting(5)==0, 'IV selector wraps maximum back to Random')
# +10/-10 retain native quantity-style clamping rather than an overshoot modulo.
number(2,2,95);select(2);m.tap(R)
check(setting(2)==100, 'Ten-step increase clamps at the numeric maximum')
number(2,2,5);select(2);m.tap(L)
check(setting(2)==1, 'Ten-step decrease clamps at the numeric minimum')
number(2,2,20);select(2)
start_delay=m.read('gKeyRepeatStartDelay',2);continue_delay=m.read('gKeyRepeatContinueDelay',2)
m.frames(RIGHT,1);first=setting(2)
m.frames(RIGHT,start_delay-1)
check(first==21 and setting(2)==first, 'Held Right changes once before the native initial-repeat delay')
m.frames(RIGHT,continue_delay*4+2);later=setting(2);m.frames(0,30)
check(later>first and later<100, 'Held Right continues incrementing through native repeat input')
stopped=setting(2);m.frames(0,continue_delay*4+2)
check(setting(2)==stopped, 'Releasing Right stops numeric auto-repeat')
m.frames(LEFT,start_delay+continue_delay*4+2);m.frames(0,30)
check(setting(2)<stopped, 'Held Left automatically decrements under native L=A mode')
number(2,2,95)
for _ in range(100):
    m.frames(RIGHT,10)
    if setting(2)<95:break
m.frames(0,30)
check(setting(2)<95 and setting(2)>=1, 'Held Right repeats across the upper boundary without sticking')
close_menu();open_menu();page(1);number(1,7,1);select(1);m.tap(LEFT)
check(setting(7)==999, 'Item quantity wraps minimum one to 999')
m.tap(RIGHT);check(setting(7)==1, 'Item quantity wraps maximum to one')
close_menu();open_menu();page(2);number(3,13,1);select(3);m.tap(LEFT)
check(setting(13)==10, 'EXP multiplier wraps 1x to 10x')
m.tap(RIGHT);check(setting(13)==1, 'EXP multiplier wraps 10x to neutral 1x')
close_menu();open_menu();page(4);number(0,19,0);select(0);m.tap(LEFT)
check(setting(19)==m.read('gPlayerPartyCount',1)-1, 'Party slot wraps only across occupied slots')
m.tap(RIGHT);check(setting(19)==0, 'Party slot wraps back to the first occupied slot')
close_menu()
# Ordinary reopen/close must work before testing the legacy combined input.
open_menu();close_menu()
check(m.callback()=='CB2_Overworld', 'Repeated Start/Mods open and close restores normal field control')
# The retired combination now follows upstream field input, which can open
# a registered-item dialog. Preserve this exact ROM's state around that probe.
m.save(out/'controls-before-old-chord.state')
m.frames(L|R|SELECT,2);m.frames(0,40)
check(not m.read('gModMenuOpen',1), 'Removed three-button chord cannot accidentally open Mods')
m.load(out/'controls-before-old-chord.state')

# Exercise all native button modes through the real Options UI.
m.save(out/'shortcut-base.state')
for mode in (0,1,2):
    start_action(5,wait=150)
    for _ in range(4):m.tap(DOWN)
    m.tap(RIGHT);m.tap(B,wait=200);m.tap(B,wait=60)
    check(m.read(m.read('gSaveBlock2Ptr')+0x13,1)==mode, f'Shortcut fixture selects native button mode {mode} through Options')
    m.frames(START,60);m.frames(START|SELECT,1);m.frames(START,40)
    check(m.read('gModMenuOpen',1) and m.read('sModPage',1)==0, f'Hold Start then a one-frame Select tap opens Main in button mode {mode}')
    check('Task_StartMenuHandleInput' not in m.tasks() and m.read('sInHelpSystem',1)==0, f'Shortcut cleans native Start menu and avoids Help in button mode {mode}')
    m.frames(START|SELECT,40)
    check(m.read('sModPage',1)==0, f'Held opening buttons cannot trigger Active review in button mode {mode}')
    m.frames(0,30);m.tap(SELECT)
    check(m.read('sModPage',1)==9, f'Select review works after releasing shortcut in button mode {mode}')
    close_menu()
    m.tap(START|SELECT,count=2,wait=60)
    check(m.read('gModMenuOpen',1) and m.read('sModPage',1)==0, f'Two-frame simultaneous Start+Select survives native menu drawing in button mode {mode}')
    close_menu();m.frames(START,1);m.tap(START|SELECT,count=1,wait=60)
    check(m.read('gModMenuOpen',1) and m.read('sModPage',1)==0, f'Shortcut tapped during native menu drawing works in button mode {mode}')
    close_menu();m.tap(START,wait=60)
    check(not m.read('gModMenuOpen',1) and 'Task_StartMenuHandleInput' in m.tasks(), f'Start alone retains native menu in button mode {mode}')
    m.tap(SELECT)
    check(not m.read('gModMenuOpen',1) and 'Task_StartMenuHandleInput' in m.tasks(), f'Select without held Start cannot steal native menu actions in button mode {mode}')
    m.tap(B,wait=60);m.save(out/'shortcut-before-select.state')
    m.tap(SELECT,wait=60)
    check(not m.read('gModMenuOpen',1) and m.read('sLockFieldControls',1), f'Select alone retains native registered-item dialog in button mode {mode}')
    m.tap(START|SELECT,wait=60)
    check(not m.read('gModMenuOpen',1), f'Scripted registered-item dialog rejects shortcut in button mode {mode}')
    m.load(out/'shortcut-before-select.state')
m.load(out/'shortcut-base.state')
m.tap(START|SELECT,wait=60);snap('shortcut-main');close_menu()
before=position();m.frames(LEFT,32);m.frames(0,30)
check(position()!=before and m.callback()=='CB2_Overworld', 'Shortcut close restores responsive ordinary gameplay')
m.frames(RIGHT,32);m.frames(0,30)
